void fast_sincos(float theta, float *s, float *c)
{
    // 归一化到 [0, 2π)
    if (theta >= TWOPI)
    {
        theta -= TWOPI * (float)((int32_t)(theta * INV_TWOPI));
    }
    if (theta < 0.0f)
    {
        theta += TWOPI * (float)((int32_t)(-theta * INV_TWOPI) + 1);
    }

    // 查表索引 + 小数部分
    float fidx = theta * TABLE_SCALE;
    int32_t idx = (int32_t)fidx;
    float frac = fidx - (float)idx;
    idx &= TABLE_MASK;

    // sin: 线性插值
    float s0 = sin_table[idx];
    float s1 = sin_table[idx + 1];
    *s = s0 + frac * (s1 - s0);

    // cos = sin(θ + π/2): 查表索引偏移 1/4
    int32_t c_idx = idx + (TABLE_SIZE >> 2);
    float c0 = sin_table[c_idx & TABLE_MASK];
    float c1 = sin_table[(c_idx + 1) & TABLE_MASK];
    *c = c0 + frac * (c1 - c0);
}
